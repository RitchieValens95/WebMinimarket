CREATE TRIGGER compra_detalle_proteger BEFORE INSERT OR UPDATE OR DELETE ON public.compras_detalles FOR EACH ROW EXECUTE FUNCTION public.sv_proteger_detalle();
CREATE TRIGGER pago_proteger BEFORE INSERT OR UPDATE OR DELETE ON public.pagos FOR EACH ROW EXECUTE FUNCTION public.sv_proteger_detalle();

CREATE FUNCTION public.sv_validar_caja_movimiento() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE cerrado timestamptz; sesion bigint; efectivo boolean; monto_pago numeric;
BEGIN
    SELECT fecha_cierre INTO STRICT cerrado FROM public.cajas_sesiones WHERE id = NEW.caja_sesion_id FOR UPDATE;
    IF cerrado IS NOT NULL THEN RAISE EXCEPTION 'La caja está cerrada.' USING ERRCODE = '23514'; END IF;
    IF NEW.pago_id IS NOT NULL THEN
        SELECT v.caja_sesion_id, p.es_efectivo, p.monto INTO STRICT sesion, efectivo, monto_pago
          FROM public.pagos p JOIN public.ventas v ON v.id = p.venta_id WHERE p.id = NEW.pago_id;
        IF NOT efectivo OR sesion <> NEW.caja_sesion_id OR monto_pago <> NEW.importe OR NEW.tipo <> 'INGRESO' THEN
            RAISE EXCEPTION 'El ingreso de caja no coincide con su pago en efectivo.' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END $fn$;
CREATE TRIGGER caja_movimiento_validar BEFORE INSERT ON public.cajas_movimientos FOR EACH ROW EXECUTE FUNCTION public.sv_validar_caja_movimiento();
CREATE FUNCTION public.sv_validar_cierre_caja() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE esperado numeric;
BEGIN
    IF OLD.fecha_cierre IS NOT NULL THEN RAISE EXCEPTION 'Una sesión cerrada es inmutable.' USING ERRCODE = '23514'; END IF;
    IF NEW.fecha_cierre IS NOT NULL THEN
        SELECT OLD.monto_inicial + coalesce(sum(CASE WHEN tipo = 'INGRESO' THEN importe ELSE -importe END), 0)
          INTO esperado FROM public.cajas_movimientos WHERE caja_sesion_id = OLD.id;
        IF NEW.efectivo_esperado IS DISTINCT FROM esperado THEN
            RAISE EXCEPTION 'El efectivo esperado no coincide con los movimientos.' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF NEW.caja_id <> OLD.caja_id OR NEW.usuario_apertura_id <> OLD.usuario_apertura_id OR NEW.fecha_apertura <> OLD.fecha_apertura OR NEW.monto_inicial <> OLD.monto_inicial THEN
        RAISE EXCEPTION 'Los datos de apertura no se pueden modificar.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $fn$;
CREATE TRIGGER caja_sesion_validar BEFORE UPDATE ON public.cajas_sesiones FOR EACH ROW EXECUTE FUNCTION public.sv_validar_cierre_caja();

-- Se validan al terminar la transacción, después de insertar todos sus registros.
CREATE FUNCTION public.sv_validar_documento_confirmado() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE identificador bigint; estado_actual text; bruto numeric; descuento_total numeric; total_doc numeric; usuario_doc bigint;
        n bigint; suma_bruto numeric; suma_descuento numeric; suma_total numeric; cobrado numeric;
BEGIN
    IF TG_TABLE_NAME = 'ventas' THEN
        identificador := NEW.id;
    ELSIF TG_TABLE_NAME IN ('ventas_detalles','pagos') THEN
        identificador := CASE WHEN TG_OP = 'DELETE' THEN OLD.venta_id ELSE NEW.venta_id END;
    ELSIF TG_TABLE_NAME = 'compras' THEN
        identificador := NEW.id;
    ELSE
        identificador := CASE WHEN TG_OP = 'DELETE' THEN OLD.compra_id ELSE NEW.compra_id END;
    END IF;
    IF TG_TABLE_NAME IN ('ventas','ventas_detalles','pagos') THEN
        SELECT estado, subtotal, descuento, total, usuario_id INTO estado_actual, bruto, descuento_total, total_doc, usuario_doc FROM public.ventas WHERE id = identificador;
        IF TG_TABLE_NAME = 'pagos' AND TG_OP <> 'DELETE' AND EXISTS (SELECT 1 FROM public.pagos WHERE id=NEW.id) AND estado_actual IS DISTINCT FROM 'CONFIRMADA' THEN
            RAISE EXCEPTION 'El pago requiere confirmar la venta en la misma transacción.' USING ERRCODE = '23514';
        END IF;
        IF estado_actual = 'CONFIRMADA' THEN
            SELECT count(*), coalesce(sum(round(cantidad * precio_unitario, 2)), 0), coalesce(sum(descuento), 0), coalesce(sum(subtotal), 0)
              INTO n, suma_bruto, suma_descuento, suma_total FROM public.ventas_detalles WHERE venta_id = identificador;
            SELECT coalesce(sum(monto), 0) INTO cobrado FROM public.pagos WHERE venta_id = identificador;
            IF n = 0 OR bruto <> suma_bruto OR descuento_total <> suma_descuento OR total_doc <> suma_total OR total_doc <> cobrado THEN
                RAISE EXCEPTION 'Venta sin detalle o con totales/pagos inconsistentes.' USING ERRCODE = '23514';
            END IF;
            IF EXISTS (SELECT 1 FROM public.ventas_detalles d WHERE d.venta_id = identificador AND NOT EXISTS (SELECT 1 FROM public.movimientos_stock m WHERE m.venta_detalle_id = d.id AND m.producto_id=d.producto_id AND m.cantidad=d.cantidad AND m.costo_unitario=d.costo_unitario)) THEN
                RAISE EXCEPTION 'Falta registrar la salida de stock de la venta.' USING ERRCODE = '23514';
            END IF;
            IF EXISTS (SELECT 1 FROM public.pagos p WHERE p.venta_id = identificador AND p.es_efectivo AND NOT EXISTS (SELECT 1 FROM public.cajas_movimientos m WHERE m.pago_id = p.id)) THEN
                RAISE EXCEPTION 'Falta registrar el ingreso de efectivo de la venta.' USING ERRCODE = '23514';
            END IF;
            IF EXISTS (SELECT 1 FROM public.cajas_movimientos m JOIN public.pagos p ON p.id=m.pago_id JOIN public.ventas v ON v.id=p.venta_id WHERE v.id=identificador AND (NOT p.es_efectivo OR m.importe<>p.monto OR m.caja_sesion_id<>v.caja_sesion_id OR m.tipo<>'INGRESO')) THEN
                RAISE EXCEPTION 'El ingreso de caja no coincide con el pago final de la venta.' USING ERRCODE = '23514';
            END IF;
            IF NOT EXISTS (SELECT 1 FROM public.auditoria WHERE entidad='ventas' AND entidad_id=identificador AND accion='VENTA_CONFIRMADA' AND usuario_id=usuario_doc) THEN
                RAISE EXCEPTION 'Falta la auditoría de confirmación de venta.' USING ERRCODE = '23514';
            END IF;
        END IF;
    ELSE
        SELECT estado, total, usuario_id INTO estado_actual, total_doc, usuario_doc FROM public.compras WHERE id = identificador;
        IF estado_actual = 'CONFIRMADA' THEN
            SELECT count(*), coalesce(sum(subtotal), 0) INTO n, suma_total FROM public.compras_detalles WHERE compra_id = identificador;
            IF n = 0 OR total_doc <> suma_total THEN RAISE EXCEPTION 'Compra sin detalle o con total inconsistente.' USING ERRCODE = '23514'; END IF;
            IF EXISTS (SELECT 1 FROM public.compras_detalles d WHERE d.compra_id = identificador AND NOT EXISTS (SELECT 1 FROM public.movimientos_stock m WHERE m.compra_detalle_id = d.id AND m.producto_id=d.producto_id AND m.cantidad=d.cantidad AND m.costo_unitario=d.costo_unitario)) THEN
                RAISE EXCEPTION 'Falta registrar la entrada de stock de la compra.' USING ERRCODE = '23514';
            END IF;
            IF NOT EXISTS (SELECT 1 FROM public.auditoria WHERE entidad='compras' AND entidad_id=identificador AND accion='COMPRA_CONFIRMADA' AND usuario_id=usuario_doc) THEN
                RAISE EXCEPTION 'Falta la auditoría de confirmación de compra.' USING ERRCODE = '23514';
            END IF;
        END IF;
    END IF;
    RETURN NULL;
END $fn$;
CREATE CONSTRAINT TRIGGER venta_confirmada_validar AFTER INSERT OR UPDATE ON public.ventas DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_validar_documento_confirmado();
CREATE CONSTRAINT TRIGGER venta_detalle_confirmado_validar AFTER INSERT OR UPDATE OR DELETE ON public.ventas_detalles DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_validar_documento_confirmado();
CREATE CONSTRAINT TRIGGER pago_confirmado_validar AFTER INSERT OR UPDATE OR DELETE ON public.pagos DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_validar_documento_confirmado();
CREATE CONSTRAINT TRIGGER compra_confirmada_validar AFTER INSERT OR UPDATE ON public.compras DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_validar_documento_confirmado();
CREATE CONSTRAINT TRIGGER compra_detalle_confirmado_validar AFTER INSERT OR UPDATE OR DELETE ON public.compras_detalles DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_validar_documento_confirmado();
$contenido$;
    calculado text := encode(sha256(convert_to(replace(bloque, chr(13) || chr(10), chr(10)), 'UTF8')), 'hex');
    registrado text;
    conflicto text;
BEGIN
    IF current_database() IN ('postgres','template0','template1') THEN
        RAISE EXCEPTION 'Seleccione la base del sistema, no una base administrativa o plantilla.';
    END IF;
    IF current_setting('server_version_num')::integer / 10000 <> 18 THEN
        RAISE EXCEPTION 'Esta versión del esquema requiere PostgreSQL 18.';
    END IF;
    IF current_setting('server_encoding') <> 'UTF8' THEN
        RAISE EXCEPTION 'La base de datos debe usar codificación UTF8.';
    END IF;
    PERFORM pg_advisory_xact_lock(783144982201);

    IF to_regclass('public.esquema_versiones') IS NOT NULL THEN
        SELECT checksum INTO registrado FROM public.esquema_versiones WHERE version = '001';
        IF registrado IS NULL THEN
            RAISE EXCEPTION 'Existe esquema_versiones sin la versión inicial reconocida. Revise la base antes de continuar.';
        END IF;
    END IF;

    IF to_regclass('public.esquema_versiones') IS NOT NULL THEN
        SELECT checksum INTO registrado FROM public.esquema_versiones WHERE version = '001';
        IF registrado IS NOT NULL THEN
            IF registrado <> calculado THEN
                RAISE EXCEPTION 'Checksum diferente para migración 001. Cree una nueva migración; no edite una versión aplicada.';
            END IF;
            RAISE NOTICE 'Migración 001 ya aplicada; no se modificaron datos.';
            RETURN;
        END IF;
    END IF;

    SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO conflicto
      FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relname = ANY(ARRAY['esquema_versiones','usuarios','roles','permisos','usuarios_roles','roles_permisos','categorias','marcas','unidades_medida','clientes','proveedores','metodos_pago','configuracion_comercio','productos','productos_codigos_barras','cajas','cajas_sesiones','ventas','ventas_detalles','pagos','compras','compras_detalles','movimientos_stock','cajas_movimientos','auditoria']);
    IF conflicto IS NOT NULL THEN
        RAISE EXCEPTION 'Ya existen objetos del sistema sin esta migración: %. No se alteraron.', conflicto;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_available_extensions WHERE name = 'pg_trgm') THEN
        RAISE EXCEPTION 'Esta instalación necesita la extensión estándar pg_trgm.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_extension e JOIN pg_catalog.pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='pg_trgm' AND n.nspname<>'public') THEN
        RAISE EXCEPTION 'pg_trgm existe en otro esquema. Revise su configuración antes de continuar.';
    END IF;

    EXECUTE bloque;
    INSERT INTO public.esquema_versiones(version, nombre, checksum)
      VALUES ('001', 'estructura', calculado);
    RAISE NOTICE 'Migración 001 aplicada correctamente.';
END $migracion$;
