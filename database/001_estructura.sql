CREATE FUNCTION public.sv_validar_movimiento_stock() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE p public.productos%ROWTYPE; anterior numeric; d_producto bigint; d_cantidad numeric;
BEGIN
    SELECT * INTO STRICT p FROM public.productos WHERE id = NEW.producto_id FOR UPDATE;
    IF NOT p.permite_decimales AND NEW.cantidad <> trunc(NEW.cantidad) THEN
        RAISE EXCEPTION 'El producto no permite cantidades fraccionadas.' USING ERRCODE = '23514';
    END IF;
    SELECT saldo_posterior INTO anterior FROM public.movimientos_stock WHERE producto_id = p.id ORDER BY id DESC LIMIT 1;
    IF NEW.saldo_anterior <> coalesce(anterior, 0) OR NEW.saldo_posterior <> p.stock_actual THEN
        RAISE EXCEPTION 'Actualice el stock y registre su movimiento coherente dentro de la misma transacción.' USING ERRCODE = '23514';
    END IF;
    IF NEW.tipo = 'SALDO_INICIAL' AND anterior IS NOT NULL THEN
        RAISE EXCEPTION 'El saldo inicial debe ser el primer movimiento.' USING ERRCODE = '23514';
    END IF;
    IF NEW.venta_detalle_id IS NOT NULL THEN
        SELECT producto_id, cantidad INTO STRICT d_producto, d_cantidad FROM public.ventas_detalles WHERE id = NEW.venta_detalle_id;
    ELSIF NEW.compra_detalle_id IS NOT NULL THEN
        SELECT producto_id, cantidad INTO STRICT d_producto, d_cantidad FROM public.compras_detalles WHERE id = NEW.compra_detalle_id;
    END IF;
    IF d_producto IS NOT NULL AND (d_producto <> p.id OR d_cantidad <> NEW.cantidad) THEN
        RAISE EXCEPTION 'El movimiento no coincide con su detalle comercial.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $fn$;
CREATE TRIGGER stock_validar BEFORE INSERT ON public.movimientos_stock FOR EACH ROW EXECUTE FUNCTION public.sv_validar_movimiento_stock();
CREATE FUNCTION public.sv_comprobar_saldo_stock() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE producto bigint; actual numeric; saldo numeric; estado_doc text;
BEGIN
    IF TG_TABLE_NAME = 'productos' THEN producto := NEW.id; ELSE producto := NEW.producto_id; END IF;
    SELECT stock_actual INTO actual FROM public.productos WHERE id = producto;
    SELECT coalesce(sum(CASE WHEN tipo IN ('SALIDA_VENTA','AJUSTE_SALIDA') THEN -cantidad ELSE cantidad END), 0)
      INTO saldo FROM public.movimientos_stock WHERE producto_id = producto;
    IF actual <> saldo THEN
        RAISE EXCEPTION 'El stock del producto % no coincide con sus movimientos.', producto USING ERRCODE = '23514';
    END IF;
    IF TG_TABLE_NAME = 'movimientos_stock' THEN
        IF NEW.venta_detalle_id IS NOT NULL THEN
            SELECT v.estado INTO estado_doc FROM public.ventas v JOIN public.ventas_detalles d ON d.venta_id=v.id WHERE d.id=NEW.venta_detalle_id;
        ELSIF NEW.compra_detalle_id IS NOT NULL THEN
            SELECT c.estado INTO estado_doc FROM public.compras c JOIN public.compras_detalles d ON d.compra_id=c.id WHERE d.id=NEW.compra_detalle_id;
        END IF;
        IF (NEW.venta_detalle_id IS NOT NULL OR NEW.compra_detalle_id IS NOT NULL) AND estado_doc IS DISTINCT FROM 'CONFIRMADA' THEN
            RAISE EXCEPTION 'Un movimiento comercial requiere confirmar su documento en la misma transacción.' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NULL;
END $fn$;
CREATE CONSTRAINT TRIGGER producto_saldo_coherente AFTER INSERT OR UPDATE ON public.productos DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_comprobar_saldo_stock();
CREATE CONSTRAINT TRIGGER movimiento_saldo_coherente AFTER INSERT ON public.movimientos_stock DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.sv_comprobar_saldo_stock();

CREATE FUNCTION public.sv_proteger_documento() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE cerrado timestamptz;
BEGIN
    IF TG_OP <> 'INSERT' AND OLD.estado = 'CONFIRMADA' THEN
        RAISE EXCEPTION 'Un documento confirmado es inmutable.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    IF TG_TABLE_NAME = 'ventas' THEN
        SELECT fecha_cierre INTO STRICT cerrado FROM public.cajas_sesiones WHERE id = NEW.caja_sesion_id FOR UPDATE;
        IF cerrado IS NOT NULL THEN RAISE EXCEPTION 'La caja está cerrada.' USING ERRCODE = '23514'; END IF;
    END IF;
    RETURN NEW;
END $fn$;
CREATE TRIGGER venta_proteger BEFORE INSERT OR UPDATE OR DELETE ON public.ventas FOR EACH ROW EXECUTE FUNCTION public.sv_proteger_documento();
CREATE TRIGGER compra_proteger BEFORE INSERT OR UPDATE OR DELETE ON public.compras FOR EACH ROW EXECUTE FUNCTION public.sv_proteger_documento();

CREATE FUNCTION public.sv_proteger_detalle() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $fn$
DECLARE estado_actual text; identificador bigint; fraccionado boolean;
BEGIN
    IF TG_TABLE_NAME IN ('ventas_detalles','pagos') THEN
        IF TG_OP <> 'INSERT' THEN
            SELECT estado INTO STRICT estado_actual FROM public.ventas WHERE id = OLD.venta_id FOR UPDATE;
            IF estado_actual = 'CONFIRMADA' THEN RAISE EXCEPTION 'La venta ya está confirmada.' USING ERRCODE = '23514'; END IF;
        END IF;
        IF TG_OP <> 'DELETE' THEN
            SELECT estado INTO STRICT estado_actual FROM public.ventas WHERE id = NEW.venta_id FOR UPDATE;
        END IF;
    ELSE
        IF TG_OP <> 'INSERT' THEN
            SELECT estado INTO STRICT estado_actual FROM public.compras WHERE id = OLD.compra_id FOR UPDATE;
            IF estado_actual = 'CONFIRMADA' THEN RAISE EXCEPTION 'La compra ya está confirmada.' USING ERRCODE = '23514'; END IF;
        END IF;
        IF TG_OP <> 'DELETE' THEN
            SELECT estado INTO STRICT estado_actual FROM public.compras WHERE id = NEW.compra_id FOR UPDATE;
        END IF;
    END IF;
    IF estado_actual = 'CONFIRMADA' THEN RAISE EXCEPTION 'El documento ya está confirmado.' USING ERRCODE = '23514'; END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    IF TG_TABLE_NAME = 'pagos' THEN
        SELECT afecta_efectivo INTO STRICT NEW.es_efectivo FROM public.metodos_pago WHERE id = NEW.metodo_pago_id;
    ELSE
        SELECT permite_decimales INTO STRICT fraccionado FROM public.productos WHERE id = NEW.producto_id;
        IF NOT fraccionado AND NEW.cantidad <> trunc(NEW.cantidad) THEN
            RAISE EXCEPTION 'El producto no permite cantidades fraccionadas.' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END $fn$;
