-- Los historiales no se corrigen sobrescribiendo operaciones anteriores.
CREATE FUNCTION public.sv_historial_inmutable() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    RAISE EXCEPTION 'El historial % no admite cambios ni eliminaciones.', TG_TABLE_NAME USING ERRCODE = '23514';
END $fn$;
CREATE TRIGGER stock_inmutable BEFORE UPDATE OR DELETE ON public.movimientos_stock FOR EACH ROW EXECUTE FUNCTION public.sv_historial_inmutable();
